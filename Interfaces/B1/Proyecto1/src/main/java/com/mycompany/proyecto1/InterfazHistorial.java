    private void mostrarContenido(File carpeta) {
        if (!carpeta.exists()) {
            txtHistorial.setText("La carpeta no existe.");
            return;
        }
        File[] ficheros = carpeta.listFiles();
        if (ficheros == null || ficheros.length == 0) {
            txtHistorial.setText("La carpeta está vacía.");
            return;
        }
        StringBuilder sb = new StringBuilder();
        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd/MM/yyyy HH:mm");
        for (File f : ficheros) {
            if (f.isFile()) {
                sb.append(f.getName()).append(" | ").append(f.length()).append(" bytes | ").append(sdf.format(new java.util.Date(f.lastModified()))) .append("\n");
            }
        }

        txtHistorial.setText(sb.toString());
    }
