private void cargarHistorial() {
    try {
        File fichero = new File("historial.txt");
        System.out.println("Ruta: " + fichero.getAbsolutePath());
        if (fichero.exists()) {
            String contenido =new String(java.nio.file.Files.readAllBytes(fichero.toPath()));
            System.out.println("CONTENIDO:");
            System.out.println(contenido);
            txtHistorial.setText(contenido);
            System.out.println("TEXTO AREA = " + txtHistorial.getText().length());
        } else {
            txtHistorial.setText("No existe historial.txt");
        }
    } catch (IOException e) {
        System.out.println("ERROR: "+e);
    }
}

