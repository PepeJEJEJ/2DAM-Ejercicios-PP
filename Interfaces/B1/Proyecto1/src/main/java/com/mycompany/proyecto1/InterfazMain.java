    private void registrarHistorial(String nombreApp) {
        // Abre el archivo en modo 'append' (true) para no sobrescribir las líneas anteriores
        try (java.io.FileWriter fw = new java.io.FileWriter("historial.txt", true)) {
            String fechaHora = java.time.LocalDateTime.now().format(java.time.format.DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm"));
            String linea = fechaHora + ";" + nombreApp + "\n";
            fw.write(linea);
            System.out.println(linea); 
        } catch (java.io.IOException e) {
            System.out.println("Error al escribir en el historial: " + e.getMessage());
        }
    }
