    private void cargarNotasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cargarNotasActionPerformed
        java.io.File fichero = new java.io.File("notas.txt");
        if (!fichero.exists()) {
            return;
        }
        try (java.util.Scanner sc = new java.util.Scanner(fichero)) {
            String texto = "";
            while (sc.hasNextLine()) {
                texto += sc.nextLine() + "\n";
            }
            txtNotas.setText(texto);
        } catch (java.io.IOException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar las notas.");
        }
    }//GEN-LAST:event_cargarNotasActionPerformed

