    private void jButtonBorrarHistActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonBorrarHistActionPerformed
        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Estás seguro de que deseas borrar todo el historial?",
            "Confirmar Borrado",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {

            java.io.File archivo = new java.io.File("historial.txt");

            if (archivo.exists()) {
                archivo.delete(); // Borra el fichero del disco
            }
            DefaultTableModel modelo = (DefaultTableModel) tablaHistorial.getModel();
            modelo.setRowCount(0); // Vacía el componente visual

            javax.swing.JOptionPane.showMessageDialog(
                this,
                "El historial ha sido borrado."
            );
        }
    }//GEN-LAST:event_jButtonBorrarHistActionPerformed

