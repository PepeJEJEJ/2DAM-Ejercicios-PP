    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        try (InputStream is = getClass().getResourceAsStream("/reporte.jrxml")) {
            if (is == null) {
                throw new IllegalStateException("No se encontró el recurso /reporte.jrxml");
            }
            JasperReport reporte
                    = JasperCompileManager.compileReport(is);

            HashMap<String, Object> parametros
                    = new HashMap<>();

            parametros.put(
                    "nombreUsuario",
                    txtNombre.getText());

            parametros.put(
                    "direccionUsuario",
                    txtDireccion.getText());

            parametros.put(
                    "telefonoUsuario",
                    txtTelefono.getText());

            parametros.put(
                    "fechaActual",
                    new SimpleDateFormat(
                            "dd/MM/yyyy HH:mm"
                    ).format(new Date()));

            JRDataSource dataSource
                    = new JREmptyDataSource();

            JasperPrint print
                    = JasperFillManager.fillReport(
                            reporte,
                            parametros,
                            dataSource
                    );

            JasperExportManager.exportReportToPdfFile(
                    print,
                    "InformeUsuario.pdf"
            );

            JasperViewer.viewReport(
                    print,
                    false
            );

            JOptionPane.showMessageDialog(
                    this,
                    "PDF generado correctamente"
            );

        } catch (Exception e) {
            e.printStackTrace();

            JOptionPane.showMessageDialog(
                    this,
                    e.getClass().getName() + "\n\n" + e.getMessage()
            );
        }
    }//GEN-LAST:event_btnGenerarActionPerformed

