    private void configurarFormularioMigLayout() {
        // Panel principal con MigLayout (2 columnas, separación y adaptación flexible)
        JPanel panel = new JPanel(new MigLayout("wrap 2, insets 20, gapy 10", "[right]rel[grow,fill]"));

        // 1. Nombre y apellidos
        panel.add(new JLabel("Nombre y apellidos:"));
        panel.add(new JTextField());

        // 2. Email
        panel.add(new JLabel("Email:"));
        panel.add(new JTextField());

        // 3. Fecha de nacimiento
        panel.add(new JLabel("Fecha de nacimiento:"));
        panel.add(new JTextField("dd/mm/aaaa"));

        // 4. Género (RadioButtons)
        panel.add(new JLabel("Género:"));
        JPanel panelGenero = new JPanel(new MigLayout("insets 0"));
        JRadioButton rbMasculino = new JRadioButton("Masculino");
        JRadioButton rbFemenino = new JRadioButton("Femenino");
        ButtonGroup bgGenero = new ButtonGroup();
        bgGenero.add(rbMasculino);
        bgGenero.add(rbFemenino);
        panelGenero.add(rbMasculino);
        panelGenero.add(rbFemenino);
        panel.add(panelGenero);

        // 5. Titulación de acceso (ComboBox)
        panel.add(new JLabel("Titulación de acceso:"));
        String[] titulaciones = {"FP Grado Medio", "FP Grado Superior", "Bachillerato"};
        panel.add(new JComboBox<>(titulaciones));

        // 6. Observaciones (crece en ancho y alto: growx, growy)
        panel.add(new JLabel("Observaciones:"));
        JTextArea txtObservaciones = new JTextArea(4, 20);
        JScrollPane scrollObservaciones = new JScrollPane(txtObservaciones);
        panel.add(scrollObservaciones, "growx, growy");

        // 7. Botones de acción (Guardar e Imprimir) alineados a la derecha
        JPanel panelBotones = new JPanel(new MigLayout("insets 0, align right"));
        JButton btnGuardar = new JButton("Guardar");
        JButton btnImprimir = new JButton("Imprimir");
        panelBotones.add(btnGuardar);
        panelBotones.add(btnImprimir);
        
        panel.add(panelBotones, "span 2, align right, gaptop 10");

        // Establecemos este panel como el contenido principal de la ventana
        this.setContentPane(panel);
        this.pack();
        this.setLocationRelativeTo(null);
    }

